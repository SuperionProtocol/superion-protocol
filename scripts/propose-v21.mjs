import 'dotenv/config';
import fs from 'fs';
import Safe from '@safe-global/protocol-kit';
import SafeApiKit from '@safe-global/api-kit';
const SAFE='0xB633ae886bbb0939E0cB7130be0D367CED9f87D4', OWNER='0xE60322A5543C2bAD26115053B586d9679F4A939f';
const RPC='https://base-rpc.publicnode.com';
let pk=process.env.PRIVATE_KEY.trim(); if(!pk.startsWith('0x')) pk='0x'+pk;
const batch=JSON.parse(fs.readFileSync('deployments/safe-batch-mainnet-v21.json'));
const S=(Safe.default&&Safe.default.init)?Safe.default:Safe; const kit=await S.init({provider:RPC,signer:pk,safeAddress:SAFE});
const owners=await kit.getOwners(); console.log('threshold',await kit.getThreshold(),'owners',owners);
const Api=SafeApiKit.default||SafeApiKit;
const api=new Api({chainId:8453n, txServiceUrl:'https://safe-transaction-base.safe.global/api', ...(process.env.SAFE_API_KEY?{apiKey:process.env.SAFE_API_KEY}:{})});
const nonce=Number(await api.getNextNonce(SAFE).catch(e=>{console.log('api nonce err',e.message);return kit.getNonce();}));
console.log('nonce',nonce,'onchain',await kit.getNonce());
const tx=await kit.createTransaction({transactions:batch.transactions.map(t=>({to:t.to,value:t.value,data:t.data})),options:{nonce}});
const h=await kit.getTransactionHash(tx); const sig=await kit.signHash(h);
const signer=(await kit.getSafeProvider().getSignerAddress());
if(signer.toLowerCase()!==OWNER.toLowerCase()) throw new Error('signer mismatch');
fs.writeFileSync('deployments/safe-v21-signed.json',JSON.stringify({safeTxHash:h,safeTxData:tx.data,signature:sig.data,sender:signer},null,2));
console.log('safeTxHash',h,'to',tx.data.to,'op',tx.data.operation);
await api.proposeTransaction({safeAddress:SAFE,safeTransactionData:tx.data,safeTxHash:h,senderAddress:signer,senderSignature:sig.data});
const p=await api.getTransaction(h); console.log('confirmations',p.confirmations.length,'/',p.confirmationsRequired,'nonce',p.nonce,'executed',p.isExecuted);
